	<h2 class="t-heading">What we collect and why</h2>
	<ul class="t-body t-2">
		<li><b>Account:</b> your name and email from your sign-in provider, and the invite code you used, to keep CareerGlobe private.</li>
		<li><b>Resume and profile:</b> the file you upload, and the skills, job titles, experience and city read from it and confirmed by you, to rank jobs for you. The file is encrypted (AES-256-GCM) and never sold or shared.</li>
		<li><b>Preferences and tracker:</b> the roles, cities and level you choose, and the jobs you save or apply to.</li>
		<li><b>Consent:</b> the date, time and policy version of your consent to upload a resume.</li>
		<li><b>Devices:</b> a push token if you allow notifications.</li>
	</ul>
	<h2 class="t-heading">How long we keep it</h2>
	<p class="t-body t-2">Resumes and profiles are deleted 12 months after your last login, after one email warning. Crawl logs are kept 90 days.</p>
	<h2 class="t-heading">Your rights (DPDP Act, 2023)</h2>
	<p class="t-body t-2">You can withdraw consent and ask for your data to be erased. Write to <a href="mailto:privacy@careerglobe.example">privacy@careerglobe.example</a> [YOUR CONTACT EMAIL]; requests are handled within 7 days. Grievance officer: [NAME].</p>
	<h2 class="t-heading">Jobs and companies</h2>
	<p class="t-body t-2">Jobs are read from each company's own careers page and shown as found, credited to the company, with a link to the full posting. Companies can ask to be removed at the same address.</p>
