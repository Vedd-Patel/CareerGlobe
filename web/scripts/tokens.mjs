// Generates src/lib/styles/tokens.css from docs/designs/tokens.json (the one
// source of design tokens for web, Android and iOS). Runs before dev/build.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, '../../docs/designs/tokens.json'), 'utf8'));
const kebab = (s) => s.replace(/[A-Z0-9]+/g, (m) => '-' + m.toLowerCase()).replace(/^-/, '');

function colors(c) {
	const out = [];
	for (const [k, v] of Object.entries(c)) {
		if (typeof v === 'string') out.push(`--${kebab(k)}: ${v};`);
		else for (const [k2, v2] of Object.entries(v)) out.push(`--${k === 'statusSoft' ? k2 + '-soft' : k2}: ${v2};`);
	}
	return out.join('\n\t');
}
const g = tokens.globe;
const shared = [
	`--font: '${tokens.font.family}', ${tokens.font.fallback};`,
	...Object.entries(tokens.radius).map(([k, v]) => `--r-${k}: ${v}px;`),
	...Object.entries(tokens.space).map(([k, v]) => `--${k}: ${v}px;`),
	...Object.entries(tokens.font.scale).map(
		([k, v]) => `--font-${k}: ${v.weight} ${v.size}px/${v.line ?? v.size + 6}px var(--font);`
	),
	`--pin-match: ${g.pinMatch};`, `--pin-hiring: ${g.pinHiring};`, `--pin-idle: ${g.pinIdle};`,
	`--ocean: ${g.ocean};`, `--land: ${g.land};`, `--border-geo: ${g.border};`,
	`--space-1: ${g.space[0]};`, `--space-2: ${g.space[1]};`, `--space-3: ${g.space[2]};`,
	`--shadow: ${tokens.elevation.card};`, `--shadow-sheet: ${tokens.elevation.sheet};`
].join('\n\t');

const light = colors(tokens.color.light);
const dark = colors(tokens.color.dark);
const css = `/* Generated by scripts/tokens.mjs from docs/designs/tokens.json — do not edit. */
:root {
	${shared}
	color-scheme: light;
	${light}
}
:root[data-theme='dark'] {
	color-scheme: dark;
	${dark}
}
@media (prefers-color-scheme: dark) {
	:root:not([data-theme='light']) {
		color-scheme: dark;
		${dark}
	}
}
`;
writeFileSync(join(here, '../src/lib/styles/tokens.css'), css);
console.log('tokens.css written');
